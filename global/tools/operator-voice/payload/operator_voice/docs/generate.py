"""Generates ``docs/generated/{INDEX,INTENTS,resources,prompts}.md``, ``docs/generated/cards/<op>.md``,
and ``docs/generated/schemas/*.json`` from the operation registry and contract schemas — build plan v3
§6/§6.3. Every function is a pure, deterministic string builder; :func:`generate_all` is the only
function that touches the filesystem, and it writes nothing but these generated files (never
hand-authored docs). Run via ``python -m operator_voice.docs.generate docs/generated`` (the checked-in
output directory; the CLI accepts any ``<output_dir>``).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from operator_voice.domain.contracts import (
    SUBJECT_INSIGHT_BUNDLE_REQUIRED_V1,
    VOICE_CONTEXT_BUNDLE_REQUIRED_V1,
)
from operator_voice.docs.prompts import render_prompts_md
from operator_voice.docs.resources import render_resources_md
from operator_voice.domain.help import challenge_description, error_taxonomy, worked_examples
from operator_voice.domain.operations import ArgType, Group, OPERATIONS, Operation
from operator_voice.interfaces.intents import ALIASES

GENERATED_HEADER = "<!-- GENERATED by operator_voice.docs.generate — do not hand-edit. -->\n"


def _arg_row(arg) -> str:
    req = "required" if arg.required else f"optional, default={arg.default!r}"
    choices = f" — one of {list(arg.choices)}" if arg.choices else ""
    return f"| `{arg.name}` | `{arg.type.value}` | {req}{choices} | {arg.help} |"


def render_operation_card(op: Operation) -> str:
    lines = [
        GENERATED_HEADER,
        f"# `{op.name}`\n",
        f"{op.summary}\n",
        f"- **group:** `{op.group.value}`",
        f"- **posture:** `{op.posture.value}`",
        f"- **CLI:** `operator-voice {op.cli_name}`",
        f"- **MCP tool:** `{op.mcp_name}`" + (" (mutation — hidden unless explicitly enabled)" if op.mutation_tool else "")
        if op.mcp_exposed
        else "- **MCP:** not exposed (CLI-only lifecycle action)",
        "",
    ]
    if op.args:
        lines += ["## Arguments\n", "| name | type | required | help |", "|---|---|---|---|"]
        lines += [_arg_row(a) for a in op.args]
        lines.append("")
    challenge = challenge_description(op)
    if challenge is not None:
        lines += ["## Confirmation\n", challenge, ""]
    # Every operation card carries at least one worked example — the curated example(s) from the
    # registry when present, otherwise a single example synthesized deterministically from the
    # operation's required arguments (noted as such, so it is never mistaken for a curated one).
    examples = worked_examples(op)
    lines += ["## Examples\n"] + [f"```\n{ex}\n```" for ex in examples]
    if not op.examples:
        lines += ["", "_Synthesized from this operation's required arguments._"]
    # A non-empty, service-grounded error taxonomy for every operation (§6 "generates ... error
    # taxonomy"). Codes are stable; meanings are plain-language and path/secret-free.
    lines += ["", "## Errors\n", "| code | what it means |", "|---|---|"]
    lines += [f"| `{e.code}` | {e.meaning} |" for e in error_taxonomy(op)]
    lines.append("")
    aliases = [phrase for name, phrases in ALIASES.items() if name == op.name for phrase in phrases]
    if aliases:
        lines += ["## Plain-language aliases\n"] + [f"- \"{p}\"" for p in aliases]
    return "\n".join(lines).rstrip() + "\n"


def render_index() -> str:
    lines = [GENERATED_HEADER, "# Operator Voice Toolkit — operation index\n"]
    for group in (Group.READ, Group.MUTATION, Group.LIFECYCLE):
        ops = [op for op in OPERATIONS if op.group == group]
        if not ops:
            continue
        lines.append(f"## {group.value}\n")
        lines.append("| operation | CLI | MCP | posture | summary |")
        lines.append("|---|---|---|---|---|")
        for op in ops:
            mcp_col = op.mcp_name if op.mcp_exposed else "—"
            lines.append(
                f"| [`{op.name}`](cards/{op.cli_name}.md) | `{op.cli_name}` | `{mcp_col}` | "
                f"{op.posture.value} | {op.summary} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_intents() -> str:
    lines = [GENERATED_HEADER, "# Deterministic intent aliases (router-off fallback)\n"]
    lines.append(
        "OVT works without an external intent router (build plan v3 D14). These plain-language "
        "phrases resolve deterministically to exactly one operation; anything else falls back to "
        "the `help` operation's ranked suggestions.\n"
    )
    lines.append("| operation | phrases |")
    lines.append("|---|---|")
    for name in sorted(ALIASES):
        phrases = ", ".join(f"\"{p}\"" for p in ALIASES[name])
        lines.append(f"| `{name}` | {phrases} |")
    return "\n".join(lines).rstrip() + "\n"


def render_schemas() -> dict[str, str]:
    return {
        "voice-context-bundle.v1.schema.json": json.dumps(
            {
                "schema": "voice-context-bundle/v1",
                "required": sorted(VOICE_CONTEXT_BUNDLE_REQUIRED_V1),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        "subject-insight-bundle.v1.schema.json": json.dumps(
            {
                "schema": "subject-insight-bundle/v1",
                "required": sorted(SUBJECT_INSIGHT_BUNDLE_REQUIRED_V1),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
    }


def generate_all(output_dir: Path) -> dict[str, str]:
    """Returns {relative_path: content} for every generated file, and writes them under
    ``output_dir`` (creating `cards/` and `schemas/` subdirectories). Deterministic: calling this
    twice with the same registry state produces byte-identical content."""
    files: dict[str, str] = {
        "INDEX.md": render_index(),
        "INTENTS.md": render_intents(),
        "resources.md": render_resources_md(),
        "prompts.md": render_prompts_md(),
    }
    for op in OPERATIONS:
        files[f"cards/{op.cli_name}.md"] = render_operation_card(op)
    for name, content in render_schemas().items():
        files[f"schemas/{name}"] = content

    for rel_path, content in files.items():
        dest = output_dir / rel_path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")
    return files


def main(argv: list[str] | None = None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    out = Path(argv[0]) if argv else Path("docs")
    files = generate_all(out)
    print(f"generated {len(files)} file(s) under {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
