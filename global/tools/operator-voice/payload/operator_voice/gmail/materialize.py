"""Gmail export materialization — OVT Gmail Adapter v1 (agent-delegated fetch, Sent-only, no token).

Turns an agent-submitted JSON envelope of the operator's own **Sent** messages (fetched agent-side
via the operator's host Gmail tools; this module never calls Google — no network, no SDK, no token,
no OAuth) into immutable, timestamp-prefixed **one-file-per-message** Markdown under the operator's
fixed ``gmail_export_dir``, ready for the ``gmail_export`` adapter to scan like any other file-tree
source.

**The hard security invariant** (enforced HERE, server-side, fail-closed — never trusted from the
calling agent's own "these are all mine, all Sent" filtering):

* **Author match.** Each message's ``from`` (or ``sender_email``) must equal the call's top-level
  self-asserted ``author_email`` — a mismatch is dropped under ``skipped_mismatched_author``, never
  silently accepted (mirrors Slack's author_id pattern).

**Identity (ADR 0002 Decision 1):** each message is a genuinely independent, immutable utterance, so
persisted document identity is ``message_id`` alone. Each message is written as its OWN immutable
file named ``<internal_date_iso>__<message_id>.md`` so plain lexicographic filename order is
chronological order — letting the ``gmail_export`` adapter reuse Slack's exact, unmodified cursor.
"""

from __future__ import annotations

from operator_voice.persistence.atomic import atomic_text

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from email.utils import parseaddr

from operator_voice.kernel.authorship import own_text
from typing import Any

MATERIALIZE_VERSION = "gmail-materialize/v2"

_MIN_CHARS = 25
_STATE_FILENAME = ".import-state.json"

_RECORD_BLOCK_RE = re.compile(
    r"<!-- ovt:gmail id=(?P<id>\S+) thread=(?P<thread>\S+) internal=(?P<internal>\S+) -->"
    r"\n##[^\n]*\n\n(?P<body>.*?)(?=\n<!-- ovt:gmail |\Z)",
    re.DOTALL,
)

_UNSAFE_FILENAME_RE = re.compile(r"[^A-Za-z0-9._-]+")


def clean_text(text: str) -> str:
    """Normalize an agent-exported plain-text Gmail body. Deliberately light — quoted reply blocks
    should already be stripped agent-side before submit; this only normalizes newlines and trims."""
    return text.replace("\r\n", "\n").replace("\r", "\n").strip()


def _keep(text: str) -> bool:
    if not text:
        return False
    if len(text) >= _MIN_CHARS:
        return True
    return "\n" in text and len(text) >= 12


def _safe_component(value: str) -> str:
    return _UNSAFE_FILENAME_RE.sub("-", value.strip()) or "unknown"


def _record_filename(internal_date: str, message_id: str) -> str:
    ts_safe = _safe_component(internal_date.replace(":", "-"))
    return f"{ts_safe}__{_safe_component(message_id)}.md"


def _sender_from_message(raw: dict) -> str:
    if "from" in raw:
        return str(raw.get("from") or "").strip()
    return str(raw.get("sender_email") or "").strip()


@dataclass(slots=True)
class MaterializeResult:
    imported: int = 0
    skipped_duplicate: int = 0
    skipped_mismatched_author: int = 0
    skipped_short: int = 0
    skipped_invalid: int = 0
    skipped_not_sent: int = 0
    skipped_auto_reply: int = 0
    skipped_delegate_sent: int = 0
    skipped_no_own_text: int = 0
    messages: set[str] = field(default_factory=set)

    def as_dict(self) -> dict[str, Any]:
        return {
            "imported": self.imported,
            "skipped_duplicate": self.skipped_duplicate,
            "skipped_mismatched_author": self.skipped_mismatched_author,
            "skipped_short": self.skipped_short,
            "skipped_invalid": self.skipped_invalid,
            "skipped_not_sent": self.skipped_not_sent,
            "skipped_auto_reply": self.skipped_auto_reply,
            "skipped_delegate_sent": self.skipped_delegate_sent,
            "skipped_no_own_text": self.skipped_no_own_text,
            "messages": sorted(self.messages),
        }


def _format_block(message_id: str, thread_id: str, internal_date: str, subject: str, body: str) -> str:
    heading = "Sent message"
    return (
        f"<!-- ovt:gmail id={message_id} thread={thread_id} internal={internal_date} -->\n"
        f"## {heading}\n\n{body}\n"
    )


def _record_header() -> str:
    return (
        "# Gmail voice capture\n\n"
        "Operator Sent mail only. Server-verified authorship "
        "(see `operator_voice.gmail.materialize`). Generated by `operator-voice gmail-import`.\n\n"
    )


def materialize(export_dir: Path, *, author_email: str, messages: list[Any]) -> MaterializeResult:
    """Write server-verified Sent messages into ``export_dir`` as immutable, timestamp-prefixed
    Markdown (one file per message — ADR 0002 Decision 1).

    ``author_email`` is the operator's own address, self-asserted for THIS call (never persisted;
    re-supplied fresh every time). Every entry in ``messages`` is verified server-side: ``from`` (or
    ``sender_email``) must equal ``author_email``, else ``skipped_mismatched_author``. Required
    fields: ``message_id``, ``thread_id``, ``internal_date`` (non-empty strings), ``text`` (a
    string). Any missing/ill-typed key → ``skipped_invalid``.

    Idempotent: a record whose ``(internal_date, message_id)`` filename already exists on disk (or
    repeats within this same batch) is counted under ``skipped_duplicate``."""
    result = MaterializeResult()
    export_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    seen_filenames: set[str] = set()

    for raw in messages:
        if not isinstance(raw, dict):
            result.skipped_invalid += 1
            continue

        sender = _sender_from_message(raw)
        if not sender or parseaddr(sender)[1].casefold() != parseaddr(author_email)[1].casefold():
            result.skipped_mismatched_author += 1
            continue

        if "labels" in raw and (not isinstance(raw["labels"], list) or "SENT" not in raw["labels"]
                                or "DRAFT" in raw["labels"] or "CHAT" in raw["labels"]):
            result.skipped_not_sent += 1
            continue
        if "auto_submitted" in raw and str(raw["auto_submitted"]).strip().casefold() != "no":
            result.skipped_auto_reply += 1
            continue
        if "sender" in raw and parseaddr(str(raw["sender"]))[1].casefold() != parseaddr(author_email)[1].casefold():
            result.skipped_delegate_sent += 1
            continue

        message_id = str(raw.get("message_id") or "").strip()
        thread_id = str(raw.get("thread_id") or "").strip()
        internal_date = str(raw.get("internal_date") or "").strip()
        text = raw.get("text")
        if not message_id or not thread_id or not internal_date or not isinstance(text, str):
            result.skipped_invalid += 1
            continue

        cleaned = clean_text(text)
        if not _keep(cleaned):
            result.skipped_short += 1
            continue

        cleaned = own_text(cleaned)
        if not cleaned:
            result.skipped_no_own_text += 1
            continue

        filename = _record_filename(internal_date, message_id)
        path = export_dir / filename
        if filename in seen_filenames or path.exists():
            result.skipped_duplicate += 1
            continue
        seen_filenames.add(filename)

        subject = str(raw.get("subject") or "").strip()
        block = _format_block(message_id, thread_id, internal_date, subject, cleaned)
        atomic_text(path, _record_header() + block)
        result.imported += 1
        result.messages.add(message_id)

    return result


def parse_export_file(text: str) -> list[dict[str, str]]:
    """Parse a materialized Gmail record file back into ``{message_id, thread_id, internal_date,
    body}`` dicts, in file order."""
    out: list[dict[str, str]] = []
    for m in _RECORD_BLOCK_RE.finditer(text):
        out.append({
            "message_id": m.group("id"),
            "thread_id": m.group("thread"),
            "internal_date": m.group("internal"),
            "body": m.group("body").strip(),
        })
    return out


def count_messages(export_dir: Path) -> int:
    """Content-free message count for ``gmail.status`` — reads only counts, never surfaces text."""
    if not export_dir.exists():
        return 0
    total = 0
    for path in sorted(export_dir.glob("*.md")):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        total += len(parse_export_file(text))
    return total


def read_import_state(export_dir: Path) -> dict[str, Any]:
    path = export_dir / _STATE_FILENAME
    if not path.exists():
        return {}
    try:
        loaded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return loaded if isinstance(loaded, dict) else {}


def write_import_state(export_dir: Path, state: dict[str, Any]) -> None:
    export_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = export_dir / _STATE_FILENAME
    atomic_text(path, json.dumps(state))


