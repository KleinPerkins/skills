def trimmed_export_text(text: str) -> tuple[str, bool]:
    """Preview and apply use the same transformation; marker bytes stay identical."""
    body_changed = False
    def trim(match):
        nonlocal body_changed
        original = match.group("body").strip()
        body = own_text(original)
        body_changed |= body != original
        marker = match.group(0).split("\n", 1)[0]
        return marker + "\n## Sent message\n\n" + body + "\n"
    return _RECORD_BLOCK_RE.sub(trim, text), body_changed


def trim_export_file(path: Path) -> bool:
    original = path.read_text(encoding="utf-8")
    trimmed, body_changed = trimmed_export_text(original)
    if trimmed != original:
        atomic_text(path, trimmed)
    return body_changed
