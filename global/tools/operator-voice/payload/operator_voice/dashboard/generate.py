def render_canvas(snapshot: dict[str, Any]) -> str:
    """Pure render: embed ``snapshot`` into the fixed render-only component. Deterministic for a
    given snapshot (keys sorted). No I/O."""
    embedded = json.dumps(snapshot, indent=2, sort_keys=True)
    return f"{_HEADER}\n{_IMPORTS}\nconst SNAPSHOT = {embedded} as const;\n{_COMPONENT}"


def generate(out_path: Path, snapshot: dict[str, Any]) -> str:
    content = render_canvas(snapshot)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return content


# Default committed product-artifact location (repo-relative).
DEFAULT_ARTIFACT_PATH = Path("dashboard/operator-voice-status.canvas.tsx")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="operator-voice-dashboard",
        description="Generate the render-only OVT status dashboard (.canvas.tsx).",
    )
    parser.add_argument("--out", default=str(DEFAULT_ARTIFACT_PATH), help="Output .canvas.tsx path")
    parser.add_argument("--sample", action="store_true",
                        help="Emit the committed synthetic sample artifact instead of live local data")
    ns = parser.parse_args(argv if argv is not None else sys.argv[1:])
    out_path = Path(ns.out)
    if ns.sample:
        generate(out_path, SAMPLE_SNAPSHOT)
        print(f"wrote sample dashboard canvas to {out_path}")
        return 0
    # Live mode: read-only snapshot from the local runtime. `dashboard.data` performs no mutation.
    from operator_voice.runtime.bootstrap import open_runtime

    runtime = open_runtime()
    try:
        snapshot = runtime.service.dashboard_data()
    finally:
        runtime.close()
    generate(out_path, snapshot)
    print(f"wrote live dashboard canvas to {out_path}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
