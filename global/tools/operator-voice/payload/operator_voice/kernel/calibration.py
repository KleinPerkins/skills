"""Frozen M1 calibration constants — build plan v3 Decision D2: "no universal 'five samples'
threshold. M1 preregisters per-facet/context calibration rules from fixtures and operator
review; uncalibrated facts remain OBSERVED."

These numbers are **evidence outputs**, not invented constants: they were selected by running
``scripts/calibrate.py`` against the synthetic fixture corpus under ``tests/fixtures/corpora/``
and recording the observed separation between "genuinely stable" and "still noisy" facets at
each candidate threshold. The full run and its reasoning are recorded in
``eval/calibration_report.json`` (generated by the same script) — see that file for the evidence
this module's constants are pinned to.

This is a *different* preregistration than the ten-dimension GA scoring rubric (§9, D21): that
rubric must be frozen **before** any M1 evidence is observed. Per-facet fact-confidence
calibration is explicitly expected to be **derived from** fixture evidence during M1 (D2) — the
discipline required here is "calibrate from evidence, then freeze," not "freeze before any
evidence exists."
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class CalibrationThresholds:
    min_documents_for_supported: int
    min_sources_for_supported: int
    max_coefficient_of_variation: float
    min_documents_for_observed: int
    # M2 (§13 worklist 3): source-diversity cap + drift. `min_sources_for_full_confidence` is the
    # source count below which a SUPPORTED fact's confidence is capped at
    # `single_source_confidence_cap` and a LOW_SOURCE_DIVERSITY review item is raised — a
    # single-source monoculture must never present as maximally confident. `drift_relative_threshold`
    # is the relative change in a fact's aggregate value that counts as material *drift* (the old
    # supported fact is deprecated/superseded and flagged for review rather than silently mutated).
    min_sources_for_full_confidence: int = 2
    single_source_confidence_cap: float = 0.8
    drift_relative_threshold: float = 0.5


# Promotion thresholds are evidence outputs (see eval/calibration_report.json for the fixture run
# that justifies them). The source-diversity cap and drift threshold are preregistered policy
# constants (build plan §13 M2 worklist 3), pinned here alongside them.
DEFAULT_CALIBRATION = CalibrationThresholds(
    min_documents_for_supported=3,
    min_sources_for_supported=1,
    max_coefficient_of_variation=0.65,
    min_documents_for_observed=1,
    min_sources_for_full_confidence=2,
    single_source_confidence_cap=0.8,
    drift_relative_threshold=0.5,
)
