"""M1 performance benchmark harness — build plan §7: "M1 benchmarks synthetic small/medium/large
corpora on the target Mac and records p50/p95 ingest, rebuild, search, context latency, peak
memory, DB growth, and context tokens. M1 then pins lightweight regression budgets as observed
baseline plus a justified margin."

Every corpus here is synthetically generated by :func:`synthetic_corpus` from a fixed seed —
never live operator transcripts (operator prompt constraint). Each run uses a fresh, disposable
SQLite DB and an in-memory keystore; nothing here touches the real Keychain, a real Git remote, or
any path outside a caller-supplied scratch directory.
"""

from __future__ import annotations

import gc
import json
import random
import resource
import statistics
import time
import tracemalloc
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from operator_voice.application.service import OperatorVoiceService
from operator_voice.persistence import migrations
from operator_voice.persistence.crypto import CryptoContext, InMemoryKeyStore
from operator_voice.persistence.sqlite import connect

BENCHMARK_VERSION = "m1-benchmark/v1"

# A small, deterministic vocabulary bank so generated sentences have real stylometric variance
# (distinct sentence lengths / punctuation / function-word rates) rather than being one repeated
# literal — synthetic, never copied from any real corpus.
_OPENERS = ("I think", "Honestly,", "In my view,", "Look,", "So,", "Frankly,", "To be clear,")
_CLAIMS = (
    "we should ship this next sprint", "the team is ready for this", "this approach is the right call",
    "we need more time before this ships", "the risk here is manageable", "this is worth the tradeoff",
    "I trust the plan we agreed on", "we should revisit this after the next review",
)
_TAILS = ("Let's go.", "That's my read.", "I feel good about it.", "We can adjust later.", "No rush though.", "")


def synthetic_corpus(size: int, seed: int = 0) -> list[str]:
    """Deterministically generate ``size`` distinct synthetic "operator voice" documents. Same
    ``(size, seed)`` always yields the same corpus (leakage-check requirement: reproducible,
    never regenerated ad hoc — see docs/eval-manifest.md)."""
    rng = random.Random(f"ovt-benchmark:{seed}:{size}")
    docs = []
    for i in range(size):
        n_sentences = rng.randint(2, 5)
        sentences = []
        for _ in range(n_sentences):
            opener = rng.choice(_OPENERS)
            claim = rng.choice(_CLAIMS)
            tail = rng.choice(_TAILS)
            sentence = f"{opener} {claim}"
            if tail:
                sentence += f" {tail}"
            else:
                sentence += "."
            sentences.append(sentence)
        docs.append(f"[doc {i}] " + " ".join(sentences))
    return docs


@dataclass(frozen=True, slots=True)
class LatencyStats:
    p50_ms: float
    p95_ms: float
    trials: int


def _percentile(samples: list[float], pct: float) -> float:
    if not samples:
        raise ValueError("_percentile() of empty sample set")
    ordered = sorted(samples)
    k = (len(ordered) - 1) * (pct / 100.0)
    f, c = int(k), min(int(k) + 1, len(ordered) - 1)
    if f == c:
        return ordered[f]
    return ordered[f] + (ordered[c] - ordered[f]) * (k - f)


def _stats(samples_ms: list[float]) -> LatencyStats:
    return LatencyStats(p50_ms=_percentile(samples_ms, 50), p95_ms=_percentile(samples_ms, 95), trials=len(samples_ms))


@dataclass(frozen=True, slots=True)
class CorpusBenchmarkResult:
    size: int
    ingest: LatencyStats
    rebuild: LatencyStats
    context_get: LatencyStats
    peak_memory_bytes: int
    db_bytes: int
    context_tokens: int


@dataclass(frozen=True, slots=True)
class BenchmarkReport:
    benchmark_version: str
    observed_at: float
    results: list[CorpusBenchmarkResult]

    def to_dict(self) -> dict[str, Any]:
        return {
            "benchmark_version": self.benchmark_version,
            "observed_at": self.observed_at,
            "results": [asdict(r) for r in self.results],
        }


def _one_trial(tmp_root: Path, corpus: list[str], trial_idx: int) -> tuple[float, float, float, int, int]:
    """Runs one full ingest -> rebuild -> context_get cycle against a fresh disposable DB.
    Returns (ingest_ms, rebuild_ms, context_get_ms, db_bytes, context_tokens)."""
    trial_dir = tmp_root / f"trial-{trial_idx}"
    trial_dir.mkdir(parents=True)
    docs_dir = trial_dir / "docs"
    docs_dir.mkdir()
    from operator_voice.slack.materialize import materialize
    materialize(docs_dir, author_id="U_BENCH", messages=[
        {"channel": "benchmark", "message_ts": f"{1700000000+i}.000100",
         "author_id": "U_BENCH", "text": text} for i, text in enumerate(corpus)
    ])

    db_path = trial_dir / "operator-voice.sqlite3"
    conn = connect(db_path)
    migrations.migrate(conn)
    try:
        crypto = CryptoContext(InMemoryKeyStore())
        service = OperatorVoiceService(conn, crypto, profile_pack_crypto=crypto)
        setup = service.setup()
        subject_id = setup["subject_id"]
        source = service.source_add(subject_id=subject_id, adapter_type="slack_export", canonical_root=str(docs_dir))

        t0 = time.perf_counter()
        ingest_result = service.ingest(source_id=source["source_id"])
        ingest_ms = (time.perf_counter() - t0) * 1000.0

        generation_id = ingest_result["generation_id"]
        t0 = time.perf_counter()
        service.rebuild(generation_id=generation_id)
        rebuild_ms = (time.perf_counter() - t0) * 1000.0

        t0 = time.perf_counter()
        bundle = service.context_get(subject_id=subject_id, consumer_id="benchmark")
        context_get_ms = (time.perf_counter() - t0) * 1000.0

        conn.commit()
        db_bytes = db_path.stat().st_size
        context_tokens = int(bundle.get("actual_tokens", 0))
        return ingest_ms, rebuild_ms, context_get_ms, db_bytes, context_tokens
    finally:
        conn.close()


def run_benchmark_suite(
    tmp_root: Path,
    sizes: tuple[int, ...] = (10, 100, 1000),
    trials_by_size: dict[int, int] | None = None,
    seed: int = 0,
) -> BenchmarkReport:
    """Runs the full small/medium/large synthetic-corpus benchmark (§7). ``tmp_root`` must be an
    empty, caller-owned scratch directory (a real filesystem — DB growth and peak memory are only
    meaningful against a real SQLite file, never an in-memory DB). Returns a
    :class:`BenchmarkReport`; the caller decides whether/how to pin it as a regression budget
    (see :func:`pin_baseline`)."""
    trials_by_size = trials_by_size or {}
    results: list[CorpusBenchmarkResult] = []
    for size in sizes:
        corpus = synthetic_corpus(size, seed=seed)
        n_trials = trials_by_size.get(size, 5 if size <= 100 else 3)
        ingest_samples, rebuild_samples, context_samples = [], [], []
        db_bytes = context_tokens = 0
        for trial in range(n_trials):
            gc.collect()
            tracemalloc.start()
            i_ms, r_ms, c_ms, db_size, tokens = _one_trial(tmp_root / f"size-{size}", corpus, trial)
            _current, peak = tracemalloc.get_traced_memory()
            tracemalloc.stop()
            ingest_samples.append(i_ms)
            rebuild_samples.append(r_ms)
            context_samples.append(c_ms)
            db_bytes = db_size
            context_tokens = tokens
        peak_rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss  # bytes on darwin, KB on linux
        results.append(CorpusBenchmarkResult(
            size=size,
            ingest=_stats(ingest_samples),
            rebuild=_stats(rebuild_samples),
            context_get=_stats(context_samples),
            peak_memory_bytes=int(peak_rss),
            db_bytes=db_bytes,
            context_tokens=context_tokens,
        ))
    return BenchmarkReport(benchmark_version=BENCHMARK_VERSION, observed_at=time.time(), results=results)


def pin_baseline(report: BenchmarkReport, margin: float = 0.5) -> dict[str, Any]:
    """§7 "pins lightweight regression budgets as observed baseline plus a justified margin."
    ``margin`` is a fractional headroom (0.5 = budget is 1.5x the observed latency/memory/growth
    value) applied uniformly — a deliberately simple, auditable policy rather than a per-metric
    tuned constant, matching D21's "no invented importance ordering after the fact" spirit."""
    budgets: dict[str, Any] = {"benchmark_version": report.benchmark_version, "margin": margin, "by_size": {}}
    for r in report.results:
        budgets["by_size"][str(r.size)] = {
            "ingest_p50_ms": r.ingest.p50_ms * (1 + margin),
            "ingest_p95_ms": r.ingest.p95_ms * (1 + margin),
            "rebuild_p50_ms": r.rebuild.p50_ms * (1 + margin),
            "rebuild_p95_ms": r.rebuild.p95_ms * (1 + margin),
            "context_get_p50_ms": r.context_get.p50_ms * (1 + margin),
            "context_get_p95_ms": r.context_get.p95_ms * (1 + margin),
            "peak_memory_bytes": r.peak_memory_bytes * (1 + margin),
            "db_bytes": r.db_bytes * (1 + margin),
        }
    return budgets


def write_baseline_file(path: Path, report: BenchmarkReport, margin: float = 0.5) -> None:
    payload = {"observed": report.to_dict(), "pinned_budget": pin_baseline(report, margin=margin)}
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")


def load_baseline_file(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text())
